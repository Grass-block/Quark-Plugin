package org.atcraftmc.starlight.music.game;

public final class MusicGameMeta {
    public String name;
    public String author;
    public String gameAuthor;

    public MusicGameMeta() {
        super();
    }

    public MusicGameMeta(final String name, final String author, final String gameAuthor) {
        this.name = name;
        this.author = author;
        this.gameAuthor = gameAuthor;
    }
}
